"""Imports the exercise catalog V2 into the app.

Usage: python -I scripts/import_exercise_catalog.py

Reads design-handoff/uebungskatalog-v2/ (format: README.md there) and writes
- src/data/exerciseCatalog.json: what lists, filters and analyses need at once
  (names, aliases, category, equipment, muscles in four roles, dose, variants).
  It is part of the main bundle, so it stays compact.
- src/data/exerciseDetails.json: setup and execution texts per exercise. The
  preview and the exercise pages load it on demand (about 220 kB gzipped), so
  the long texts stay out of the main bundle.
- src/data/equipment.js: all equipment of the catalog. Existing IDs keep the
  names the app already uses.
The movement data (joint angles, camera, contacts) and sources stay out of the
app; only the graphics team needs them.

Duplicates are merged here: the dropped ID is listed in `legacyIds` and
resolves to the kept one, so plans that use it stay valid.
"""
import json
import pathlib
import re

ROOT = pathlib.Path(__file__).resolve().parent.parent
CATALOG = ROOT / 'design-handoff' / 'uebungskatalog-v2'
DATA = ROOT / 'src' / 'data'
EXISTING_IDS = ROOT / 'scripts' / 'existing_exercise_ids.json'

# Dropped ID -> kept ID. Both describe a prone Y raise on an incline bench;
# prone_y_raise is kept because other exercises already link to it.
MERGED = {
    'incline_y_raise': 'prone_y_raise',
}

CORE_FIELDS = ('id', 'name', 'aliases', 'category', 'mechanics', 'pattern', 'level', 'laterality', 'perSide',
               'equipment', 'muscles', 'dose', 'variants', 'regression', 'progression')
ROLES = ('primary', 'secondary', 'stabilizers', 'stretched')


def load_exercises():
    exercises = []
    for path in sorted((CATALOG / 'uebungen').glob('*.json')):
        exercises.extend(json.loads(path.read_text(encoding='utf-8')))
    return exercises


def unique(items):
    return list(dict.fromkeys(items))


def merge_duplicates(exercises):
    by_id = {exercise['id']: exercise for exercise in exercises}
    for dropped, kept in MERGED.items():
        source, target = by_id[dropped], by_id[kept]
        for language in ('de', 'en'):
            names = [source['name'][language], *source['aliases'].get(language, [])]
            own = {target['name'][language].lower()}
            target['aliases'][language] = unique(
                [*target['aliases'].get(language, []), *(name for name in names if name.lower() not in own)])
        target['variants'] = unique([*target['variants'], *source['variants']])
    exercises = [exercise for exercise in exercises if exercise['id'] not in MERGED]
    # Links to a dropped exercise point to the kept one.
    resolve = lambda ref: MERGED.get(ref, ref)
    for exercise in exercises:
        exercise['variants'] = unique(v for v in map(resolve, exercise['variants']) if v != exercise['id'])
        for field in ('regression', 'progression'):
            if exercise.get(field):
                exercise[field] = resolve(exercise[field])
    return exercises


def core(exercise):
    entry = {field: exercise[field] for field in CORE_FIELDS}
    entry['muscles'] = {role: exercise['muscles'].get(role, []) for role in ROLES}
    entry['mediaPriority'] = exercise['media']['priority']
    return entry


def details(exercise):
    return {'setup': exercise['setup'], 'execution': exercise['execution']}


def check(exercises):
    ids = [exercise['id'] for exercise in exercises]
    assert len(ids) == len(set(ids)), 'duplicate IDs'
    known = set(ids)
    missing = set(json.loads(EXISTING_IDS.read_text(encoding='utf-8'))) - known
    assert not missing, f'existing IDs missing: {sorted(missing)}'
    for exercise in exercises:
        for ref in [*exercise['variants'], exercise['regression'], exercise['progression']]:
            assert ref is None or ref in known, f"{exercise['id']}: unknown link {ref}"
        roles = [muscle for role in ROLES for muscle in exercise['muscles'].get(role, [])]
        assert len(roles) == len(set(roles)), f"{exercise['id']}: muscle in two roles"


def js_string(text):
    return "'" + text.replace('\\', '\\\\').replace("'", "\\'") + "'"


def write_equipment():
    target = DATA / 'equipment.js'
    current = dict((match[0], (match[1], match[2])) for match in re.findall(
        r"^  (\w+): \{ de: '([^']*)', en: '([^']*)'", target.read_text(encoding='utf-8'), re.M))
    catalog = json.loads((CATALOG / 'geraete.json').read_text(encoding='utf-8'))['equipment']
    lines = [
        '// Equipment used by the exercises, generated by scripts/import_exercise_catalog.py',
        '// from design-handoff/uebungskatalog-v2/geraete.json. IDs follow the graphics package',
        '// catalog. `kind` groups the equipment: free_weight, machine, bench_rack, band,',
        '// bodyweight_aid, cardio_machine, combat, mobility_aid, surface.',
        'export const EQUIPMENT = {',
    ]
    for item in sorted(catalog, key=lambda item: item['id']):
        de, en = current.get(item['id'], (item['name']['de'], item['name']['en']))
        lines.append(f"  {item['id']}: {{ de: {js_string(de)}, en: {js_string(en)}, kind: {js_string(item['kind'])} }},")
    lines.append('};')
    target.write_text('\n'.join(lines) + '\n', encoding='utf-8')
    return len(catalog), len(catalog) - len(current)


def dump_lines(items, opening, closing):
    # One exercise per line keeps the files compact and the diffs readable.
    body = ',\n'.join(json.dumps(item, ensure_ascii=False, separators=(',', ':')) for item in items)
    return f'{opening}\n{body}\n{closing}\n'


def main():
    exercises = merge_duplicates(load_exercises())
    check(exercises)
    exercises.sort(key=lambda exercise: exercise['id'])
    header = json.dumps({'legacyIds': MERGED}, separators=(',', ':'))[:-1]
    (DATA / 'exerciseCatalog.json').write_text(
        dump_lines([core(exercise) for exercise in exercises], header + ',"exercises":[', ']}'), encoding='utf-8')
    detail_lines = ',\n'.join(
        f'{json.dumps(exercise["id"])}:{json.dumps(details(exercise), ensure_ascii=False, separators=(",", ":"))}'
        for exercise in exercises)
    (DATA / 'exerciseDetails.json').write_text('{\n' + detail_lines + '\n}\n', encoding='utf-8')
    equipment, added = write_equipment()
    print(f'Wrote {len(exercises)} exercises ({len(MERGED)} merged), {equipment} equipment ({added} new).')


if __name__ == '__main__':
    main()
